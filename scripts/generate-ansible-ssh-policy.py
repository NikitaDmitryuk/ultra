"""Bundle the shared SSH policy for Ansible hosts without installed recovery tools."""
import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_source():
    source = (ROOT / 'deploy/recovery/ssh_policy.py').read_text()
    tree = ast.parse(source)
    options = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == 'ssh_options')
    policy = json.loads((ROOT / 'deploy/recovery/ssh_policy.json').read_text())
    return ('# Generated by scripts/generate-ansible-ssh-policy.py; do not edit.\n'
            '# Ansible bundles module_utils into the remote module payload.\n'
            'POLICY = ' + repr(policy) + '\n\n\n' + ast.get_source_segment(source, options) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'deploy/ansible/module_utils/ultra_ssh_policy.py'
    content = generated_source()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('Ansible SSH policy is stale; run make format')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
