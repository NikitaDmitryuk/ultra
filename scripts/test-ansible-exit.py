#!/usr/bin/env python3
"""Actual SSH/Ansible exit-role test in a disposable container, without production inputs."""
import argparse
from contextlib import contextmanager
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shutil
import re
import stat
import subprocess
import tempfile
import time
import uuid

ROOT = Path(__file__).resolve().parents[1]
NAMESPACE = Path('/var/lib/ultra-ansible')
CONTROLLER_PYTHON = Path('/usr/bin/python3')
MANAGED_UNIT_FILES = tuple(Path(root) / 'ultra-ansible-controller.service' for root in (
    '/etc/systemd/system', '/run/systemd/system', '/usr/lib/systemd/system'))


def run(arguments, **kwargs):
    result = subprocess.run(arguments, check=False, stdout=subprocess.PIPE, stderr=subprocess.PIPE, **kwargs)
    if result.returncode:
        print('fixture command failed: ' + Path(arguments[0]).name +
              ' exit=' + str(result.returncode), flush=True)
        if Path(arguments[0]).name == 'ultra-install':
            # Print classifications, never arbitrary command output or inputs.
            codes = sorted(set(re.findall(
                r'\b(?:execution|ansible|controller|job|operation|lifecycle|exit_preparation)_[a-z_]{1,80}\b',
                result.stderr.decode(errors='replace'))))
            print('fixture installer codes: ' + ','.join(codes or ['unclassified_failure']), flush=True)
        if arguments[0] == 'ssh':
            # This endpoint and its credentials are generated by this driver.
            print(result.stderr.decode(), flush=True)
        result.check_returncode()
    return result.stdout.decode().strip()


def fixture_preflight():
    if os.geteuid() != 0:
        raise ValueError('fixture_requires_explicit_root_driver_on_disposable_systemd_host')
    if NAMESPACE.exists() or NAMESPACE.is_symlink():
        raise ValueError('fixture_canonical_namespace_preexists')
    if any(path.exists() or path.is_symlink() for path in MANAGED_UNIT_FILES):
        raise ValueError('fixture_managed_controller_preexists')
    for executable in (CONTROLLER_PYTHON, Path('/usr/bin/systemctl'), Path('/usr/bin/systemd-run')):
        resolved = executable.resolve(strict=True)
        for member in [resolved, *resolved.parents]:
            info = member.lstat()
            if info.st_uid != 0 or info.st_mode & 0o022:
                raise ValueError('fixture_controller_runtime_not_root_owned')
        if not resolved.is_file() or not os.access(resolved, os.X_OK):
            raise ValueError('fixture_controller_runtime_unavailable')
    if not run(['/usr/bin/systemctl', 'show', '--property=Version', '--value']):
        raise ValueError('fixture_actual_systemd_manager_required')
    loaded = run(['/usr/bin/systemctl', 'show', 'ultra-ansible-controller.service', '--property=LoadState'])
    if loaded != 'LoadState=not-found':
        raise ValueError('fixture_managed_controller_preexists')
    if run(['/usr/bin/systemctl', 'list-units', '--all', '--no-legend', '--plain', 'ultra-*.service']):
        raise ValueError('fixture_existing_ultra_unit')


def private_json(path):
    info = path.lstat()
    if (info.st_uid != 0 or info.st_mode & 0o077 or not stat.S_ISREG(info.st_mode)
            or info.st_nlink != 1 or info.st_size > 4 * 1024 * 1024):
        raise ValueError('fixture_evidence_not_private')
    return json.loads(path.read_bytes())


def cleanup_owned_fixture(directory, owner):
    for path in (directory, NAMESPACE):
        info = path.lstat()
        if info.st_uid != 0 or info.st_mode & 0o077 or not stat.S_ISDIR(info.st_mode):
            raise ValueError('fixture_owned_directory_changed')
    if private_json(NAMESPACE / '.fixture-owner.json') != owner:
        raise ValueError('fixture_namespace_ownership_changed')
    if {entry.name for entry in NAMESPACE.iterdir()} - {'.fixture-owner.json', 'execution-admission.lock'}:
        raise ValueError('fixture_namespace_has_uncertain_or_foreign_evidence')
    jobs = [path for path in (directory / 'state').iterdir() if path.is_dir()]
    if not jobs:
        raise ValueError('fixture_normal_completion_missing')
    for job in jobs:
        info = job.lstat()
        if info.st_uid != 0 or info.st_mode & 0o077 or not stat.S_ISDIR(info.st_mode):
            raise ValueError('fixture_owned_job_directory_changed')
        if not re.fullmatch(r'[a-f0-9-]{36}', job.name):
            raise ValueError('fixture_foreign_job_directory')
        receipt = private_json(job / 'receipt.json')
        completion_raw = (job / 'execution-completion.json').read_bytes()
        completion = private_json(job / 'execution-completion.json')
        fence = completion['fence']
        generation = fence['generation']
        if not re.fullmatch('[a-f0-9]{32}', generation):
            raise ValueError('fixture_execution_generation_invalid')
        drain = private_json(job / ('execution-drain-' + generation + '.json'))
        proof = private_json(job / 'execution-containment.json')
        if (receipt.get('state') != 'succeeded' or receipt.get('execution_generation') != generation
                or completion.get('local_cleanup') is not True
                or completion.get('receipt_sha256') != hashlib.sha256((job / 'receipt.json').read_bytes()).hexdigest()
                or fence.get('job_directory') != str(job) or proof.get('fence') != fence
                or drain.get('proof') != proof
                or drain.get('completion_sha256') != hashlib.sha256(completion_raw).hexdigest()
                or proof.get('mode') != 'transient'
                or proof.get('unit') != 'ultra-execution-' + generation + '.service'):
            raise ValueError('fixture_exact_normal_cleanup_unverified')
        unit = proof['unit']
        observed = run(['/usr/bin/systemctl', 'show', unit, '--property=LoadState', '--property=ActiveState'])
        values = dict(line.split('=', 1) for line in observed.splitlines() if '=' in line)
        if values.get('LoadState') != 'not-found' and values.get('ActiveState') not in ('inactive', 'failed'):
            raise ValueError('fixture_execution_unit_not_drained')
        events = Path('/sys/fs/cgroup/system.slice') / unit / 'cgroup.events'
        if events.exists() and 'populated 0\n' not in events.read_text():
            raise ValueError('fixture_execution_cgroup_not_empty')
    # Only our initially absent namespace may be removed, while holding its
    # admission lock after the worker and every exact execution unit have exited.
    lock_path = NAMESPACE / 'execution-admission.lock'
    info = lock_path.lstat()
    if info.st_uid != 0 or info.st_mode & 0o077 or not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise ValueError('fixture_admission_lock_changed')
    with os.fdopen(os.open(lock_path, os.O_RDWR | os.O_NOFOLLOW), 'r+b') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        if private_json(NAMESPACE / '.fixture-owner.json') != owner or (
                {entry.name for entry in NAMESPACE.iterdir()} != {'.fixture-owner.json', 'execution-admission.lock'}):
            raise ValueError('fixture_namespace_changed_during_cleanup')
        (NAMESPACE / '.fixture-owner.json').unlink()
        (NAMESPACE / 'execution-admission.lock').unlink()
        NAMESPACE.rmdir()
    shutil.rmtree(directory)


@contextmanager
def fixture_workspace(installer):
    directory = Path(tempfile.mkdtemp(prefix='ultra-ansible-fixture-'))
    owner = {'schema': 1, 'directory': str(directory), 'identity': uuid.uuid4().hex}
    # Exclusive creation, never replace or clear an existing controller root.
    NAMESPACE.mkdir(mode=0o700)
    marker = NAMESPACE / '.fixture-owner.json'
    with marker.open('x') as stream:
        marker.chmod(0o600)
        json.dump(owner, stream)
        stream.flush()
        os.fsync(stream.fileno())
    try:
        copied = directory / 'ultra-install'
        shutil.copyfile(installer, copied)
        copied.chmod(0o700)
        yield directory
        cleanup_owned_fixture(directory, owner)
    except BaseException:
        print('fixture evidence retained: ' + str(directory) + ' and ' + str(NAMESPACE), flush=True)
        raise


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--installer', required=True)
    parser.add_argument('--ansible-playbook', required=True)
    parser.add_argument('--runtime', help='optional offline Python 3.12 runtime archive')
    arguments = parser.parse_args()
    fixture_preflight()
    arguments.ansible_playbook = str(Path(arguments.ansible_playbook).resolve(strict=True))
    if 'core 2.20.0' not in run([arguments.ansible_playbook, '--version']):
        raise ValueError('fixture_pinned_ansible_required')
    image = 'ultra-ansible-exit-fixture'
    run(['docker', 'build', '-q', '-t', image, str(ROOT / 'deploy/ansible/tests')])
    with fixture_workspace(arguments.installer) as directory:
        arguments.installer = str(directory / 'ultra-install')
        identity = directory / 'identity'
        run(['ssh-keygen', '-q', '-t', 'ed25519', '-N', '', '-f', str(identity)])
        container = run(['docker', 'run', '-d', '--network', 'bridge', '-p', '127.0.0.1::22', image])
        worker = None
        try:
            if arguments.runtime:
                run(['docker', 'cp', arguments.runtime, container + ':/tmp/runtime.tar.gz'])
                run(['docker', 'exec', container, 'mkdir', '-p', '/tmp/runtime'])
                run(['docker', 'exec', container, 'tar', '-xzf', '/tmp/runtime.tar.gz', '-C', '/tmp/runtime'])
                run(['docker', 'exec', container, 'python3', '-m', 'venv', '/tmp/runtime-venv'])
                run(['docker', 'exec', container, '/tmp/runtime-venv/bin/pip', 'install', '--no-index',
                     '--require-hashes', '--find-links=/tmp/runtime/wheels', '-r', '/tmp/runtime/requirements.lock'])
                assert 'core 2.20.0' in run(['docker', 'exec', container, '/tmp/runtime-venv/bin/ansible-playbook', '--version'])
            run(['docker', 'cp', str(ROOT / 'deploy/ansible/tests/ufw.py'), container + ':/usr/sbin/ufw'])
            run(['docker', 'exec', container, 'chmod', '755', '/usr/sbin/ufw'])
            port = int(run(['docker', 'port', container, '22/tcp']).split(':')[-1])
            run(['docker', 'cp', str(identity.with_suffix('.pub')), container + ':/root/.ssh/authorized_keys'])
            run(['docker', 'exec', container, 'chown', 'root:root', '/root/.ssh/authorized_keys'])
            run(['docker', 'exec', container, 'chmod', '600', '/root/.ssh/authorized_keys'])
            key = run(['docker', 'exec', container, 'cat', '/etc/ssh/ssh_host_ed25519_key.pub']).split()
            known_hosts = directory / 'known_hosts'
            known_hosts.write_text(f'[127.0.0.1]:{port} {key[0]} {key[1]}\n')
            known_hosts.chmod(0o600)
            # Confirm the same pinned SSH endpoint before involving Ansible.
            run(['ssh', '-F', '/dev/null', '-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=yes',
                 '-o', 'UserKnownHostsFile=' + str(known_hosts), '-p', str(port), '-i', str(identity),
                 'root@127.0.0.1', 'true'])
            binary = directory / 'ultra-relay'
            binary.write_text('#!/bin/sh\nexit 0\n')
            request = {
                'host': '127.0.0.1', 'port': port, 'user': 'root', 'identity': str(identity),
                'known_hosts': str(known_hosts), 'bridge_ipv4': '192.0.2.1',
                'spec': {'role': 'exit', 'schema_version': 1, 'mimic_preset': 'steamlike',
                         'listen_address': '0.0.0.0', 'vless_port': 8443,
                         'splithttp_host': 'example.com', 'splithttp_path': '/fixture',
                         'exit': {'tunnel_uuid': str(uuid.uuid4())},
                         'exit_cert': {'cert_file': '/etc/ultra-relay/fullchain.pem', 'key_file': '/etc/ultra-relay/privkey.pem'}},
            }
            request_file = directory / 'request.json'
            request_file.write_text(json.dumps(request))
            request_file.chmod(0o600)
            socket = directory / 'worker.sock'
            worker = subprocess.Popen([arguments.installer, 'ansible-controller', '--state', str(directory / 'state'),
                                       '--socket', str(socket), '--python', str(CONTROLLER_PYTHON),
                                       '--executable', arguments.ansible_playbook, '--allowed-user', 'root'],
                                      stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
            deadline = time.monotonic() + 10
            while not socket.exists() and time.monotonic() < deadline:
                if worker.poll() is not None:
                    raise ValueError('fixture controller exited')
                time.sleep(0.05)
            pins = []
            restart_counts = []
            for _ in range(2):
                operation = str(uuid.uuid4())
                try:
                    run([arguments.installer, 'ansible-exit', '--socket', str(socket), '--request', str(request_file),
                         '--binary', str(binary), '--id', operation], timeout=180)
                except subprocess.CalledProcessError:
                    receipt = directory / 'state' / operation / 'receipt.json'
                    if receipt.exists():
                        value = json.loads(receipt.read_text())
                        code = value.get('diagnostic', {}).get('code', value.get('code', 'fixture_failed'))
                        print('fixture diagnostic: ' + (code if isinstance(code, str) and re.fullmatch('[a-z_]{1,80}', code) else 'unclassified_failure'), flush=True)
                    raise
                result = json.loads((directory / 'state' / operation / 'receipt.json').read_text())
                pins.append(result['result']['cert_pin'])
                restart_counts.append(json.loads(run(['docker', 'exec', container, 'cat', '/var/lib/fixture-systemctl.json']))['activations'])
            assert pins[0] == pins[1], 'certificate was rotated on repeated configuration'
            state = json.loads(run(['docker', 'exec', container, 'cat', '/var/lib/fixture-systemctl.json']))
            assert state['active'] and state['enabled']
            assert restart_counts[0] >= 1 and restart_counts[0] == restart_counts[1], 'unchanged configuration restarted the service: ' + str(restart_counts)
            installed = json.loads(run(['docker', 'exec', container, 'cat', '/etc/ultra-relay/spec.json']))
            assert installed['exit']['tunnel_uuid'] == request['spec']['exit']['tunnel_uuid'], 'route UUID changed'
            # A configuration string must stay literal rather than evaluate a lookup on the controller.
            sentinel = directory / 'template-injection'
            request['spec']['splithttp_path'] = "/{{ lookup('ansible.builtin.pipe', 'touch " + str(sentinel) + "') }}"
            request_file.write_text(json.dumps(request))
            operation = str(uuid.uuid4())
            run([arguments.installer, 'ansible-exit', '--socket', str(socket), '--request', str(request_file),
                 '--binary', str(binary), '--id', operation], timeout=180)
            assert not sentinel.exists(), 'peer configuration evaluated a controller lookup'
            installed = json.loads(run(['docker', 'exec', container, 'cat', '/etc/ultra-relay/spec.json']))
            assert installed['splithttp_path'] == request['spec']['splithttp_path'], 'literal configuration changed'
            calls = json.loads(run(['docker', 'exec', container, 'cat', '/var/lib/fixture-ufw.json']))
            expected = ['allow', 'from', request['bridge_ipv4'], 'to', 'any', 'port', str(request['spec']['vless_port']), 'proto', 'tcp']
            assert calls == [expected], 'firewall exposed more than the pinned bridge path'
            run(['docker', 'exec', container, 'touch', '/var/lib/fixture-ufw-inactive'])
            run([arguments.installer, 'ansible-exit', '--socket', str(socket), '--request', str(request_file), '--binary', str(binary), '--id', str(uuid.uuid4())], timeout=180)
            assert json.loads(run(['docker', 'exec', container, 'cat', '/var/lib/fixture-ufw.json'])) == calls, 'inactive firewall was modified'
            print('SSH/Ansible exit-role fixture passed with actual local systemd containment; target service manager and tunnel payload remain outside this fixture')
        finally:
            if worker:
                worker.terminate()
                try:
                    worker.communicate(timeout=10)
                except subprocess.TimeoutExpired:
                    worker.kill()
                    worker.communicate()
            subprocess.run(['docker', 'rm', '-f', container], check=False, stdout=subprocess.DEVNULL)


if __name__ == '__main__':
    main()
